-- S2-05: a faixa térmica passa a pertencer a uma política versionada (ADR 0003, seção 2).
-- Cada câmara existente vira a versão 1 da sua política, com a mesma faixa e o limiar inicial de demonstração (3).

CREATE TABLE politicas_termicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- A câmara nunca é apagada pela aplicação (só inativada); a cascata existe para que a remoção física de uma
    -- câmara, feita apenas na limpeza de testes, leve junto as versões que só fazem sentido com ela.
    camara_id BIGINT NOT NULL CONSTRAINT fk_politicas_camara REFERENCES camaras(id) ON DELETE CASCADE,
    versao INT NOT NULL CONSTRAINT chk_politicas_versao CHECK (versao >= 1),
    temperatura_minima NUMERIC(4,1) NOT NULL,
    temperatura_maxima NUMERIC(4,1) NOT NULL,
    limiar INT NOT NULL CONSTRAINT chk_politicas_limiar CHECK (limiar BETWEEN 1 AND 100),
    -- Nulo quando não há autor identificado, como na versão inicial criada por esta migração.
    autor_id UUID CONSTRAINT fk_politicas_autor REFERENCES usuarios(id),
    criada_em TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_politicas_camara_versao UNIQUE (camara_id, versao),
    CONSTRAINT chk_politicas_faixa CHECK (temperatura_minima < temperatura_maxima)
);

INSERT INTO politicas_termicas (camara_id, versao, temperatura_minima, temperatura_maxima, limiar, autor_id, criada_em)
SELECT id, 1, temperatura_minima, temperatura_maxima, 3, NULL, criado_em
FROM camaras;

-- Estado térmico independente do estado operacional. Toda câmara começa sem leituras: nenhuma medição é inventada.
ALTER TABLE camaras ADD COLUMN estado_termico VARCHAR(20) NOT NULL DEFAULT 'SEM_LEITURAS'
    CONSTRAINT chk_camaras_estado_termico
        CHECK (estado_termico IN ('SEM_LEITURAS', 'NORMAL', 'ATENCAO', 'EM_ALERTA'));
ALTER TABLE camaras ALTER COLUMN estado_termico DROP DEFAULT;

-- A política é a única fonte oficial da faixa: as colunas antigas deixam de existir para não haver duas versões.
ALTER TABLE camaras DROP CONSTRAINT chk_faixa_termica;
ALTER TABLE camaras DROP COLUMN temperatura_minima;
ALTER TABLE camaras DROP COLUMN temperatura_maxima;
