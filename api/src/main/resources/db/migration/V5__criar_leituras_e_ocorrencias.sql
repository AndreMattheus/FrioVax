-- S2-06: leituras, ocorrências térmicas, evidências e fotografia dos lotes afetados (ADR 0003, seções 3 a 5).
-- Tudo em SQL transacional: se algo falhar, a migração inteira é desfeita.
-- A aplicação nunca apaga câmaras (só inativa). Como na V4, a cascata por câmara existe apenas para a limpeza física
-- feita nos testes; lotes e leituras referenciados pelo histórico não têm cascata.

CREATE TABLE leituras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camara_id BIGINT NOT NULL CONSTRAINT fk_leituras_camara REFERENCES camaras (id) ON DELETE CASCADE,
    -- Chave externa enviada pelo sensor; não é normalizada (ADR 0003, seção 5).
    id_externo VARCHAR(100) NOT NULL CONSTRAINT chk_leituras_id_externo CHECK (length(id_externo) > 0),
    instante TIMESTAMPTZ NOT NULL,
    temperatura NUMERIC(4,1) NOT NULL,
    origem VARCHAR(100) NOT NULL CONSTRAINT chk_leituras_origem CHECK (length(origem) > 0),
    politica_versao INT NOT NULL,
    classificacao VARCHAR(10) NOT NULL CONSTRAINT chk_leituras_classificacao
        CHECK (classificacao IN ('SEGURA', 'INSEGURA')),
    sequencia INT NOT NULL,
    limiar_atingido BOOLEAN NOT NULL,
    aceita_em TIMESTAMPTZ NOT NULL,
    -- Idempotência: a mesma chave nunca é gravada duas vezes, nem com requisições concorrentes.
    CONSTRAINT uk_leituras_camara_id_externo UNIQUE (camara_id, id_externo),
    -- Ordem estrita: duas leituras da mesma câmara não têm o mesmo instante.
    CONSTRAINT uk_leituras_camara_instante UNIQUE (camara_id, instante),
    -- A leitura conserva a versão da política usada no cálculo.
    CONSTRAINT fk_leituras_politica FOREIGN KEY (camara_id, politica_versao)
        REFERENCES politicas_termicas (camara_id, versao),
    -- Resultado coerente: segura tem sequência 0; insegura, de 1 a 100; só insegura atinge o limiar.
    CONSTRAINT chk_leituras_resultado CHECK (
        (classificacao = 'SEGURA' AND sequencia = 0 AND NOT limiar_atingido)
        OR (classificacao = 'INSEGURA' AND sequencia BETWEEN 1 AND 100))
);

-- Janela de análise: últimas leituras da câmara na versão de política vigente.
CREATE INDEX idx_leituras_camara_politica_instante ON leituras (camara_id, politica_versao, instante DESC);

CREATE TABLE ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camara_id BIGINT NOT NULL CONSTRAINT fk_ocorrencias_camara REFERENCES camaras (id) ON DELETE CASCADE,
    politica_versao INT NOT NULL,
    leitura_abertura_id BIGINT NOT NULL CONSTRAINT fk_ocorrencias_leitura_abertura REFERENCES leituras (id),
    aberta_em TIMESTAMPTZ NOT NULL,
    resolvida_em TIMESTAMPTZ,
    -- Nulo enquanto a autoria não for repassada pela API (ver S2-12).
    resolvida_por UUID CONSTRAINT fk_ocorrencias_resolvida_por REFERENCES usuarios (id),
    justificativa VARCHAR(500),
    leitura_resolucao_id BIGINT CONSTRAINT fk_ocorrencias_leitura_resolucao REFERENCES leituras (id),
    -- Uma leitura abre no máximo uma ocorrência.
    CONSTRAINT uk_ocorrencias_leitura_abertura UNIQUE (leitura_abertura_id),
    CONSTRAINT fk_ocorrencias_politica FOREIGN KEY (camara_id, politica_versao)
        REFERENCES politicas_termicas (camara_id, versao),
    -- Aberta: sem nenhum dado de resolução. Resolvida: com justificativa e leitura, depois da abertura.
    CONSTRAINT chk_ocorrencias_resolucao CHECK (
        (resolvida_em IS NULL AND resolvida_por IS NULL AND justificativa IS NULL AND leitura_resolucao_id IS NULL)
        OR (resolvida_em IS NOT NULL AND resolvida_em >= aberta_em
            AND justificativa IS NOT NULL AND length(justificativa) > 0 AND leitura_resolucao_id IS NOT NULL))
);

-- No máximo uma ocorrência aberta por câmara (ADR 0003, seção 4), garantido também no banco.
CREATE UNIQUE INDEX uk_ocorrencias_aberta_por_camara ON ocorrencias (camara_id) WHERE resolvida_em IS NULL;
CREATE INDEX idx_ocorrencias_camara_abertura ON ocorrencias (camara_id, aberta_em DESC, id DESC);

-- Leituras que formaram a sequência da ocorrência, na ordem em que aconteceram.
CREATE TABLE ocorrencia_evidencias (
    ocorrencia_id BIGINT NOT NULL
        CONSTRAINT fk_evidencias_ocorrencia REFERENCES ocorrencias (id) ON DELETE CASCADE,
    leitura_id BIGINT NOT NULL CONSTRAINT fk_evidencias_leitura REFERENCES leituras (id),
    posicao INT NOT NULL CONSTRAINT chk_evidencias_posicao CHECK (posicao >= 1),
    CONSTRAINT pk_ocorrencia_evidencias PRIMARY KEY (ocorrencia_id, leitura_id),
    CONSTRAINT uk_evidencias_posicao UNIQUE (ocorrencia_id, posicao)
);

CREATE INDEX idx_evidencias_leitura ON ocorrencia_evidencias (leitura_id);

-- Fotografia dos lotes no momento da abertura. Copia identidade e quantidade: mover, dar baixa ou inativar o lote
-- depois não altera estas linhas.
CREATE TABLE ocorrencia_lotes (
    ocorrencia_id BIGINT NOT NULL CONSTRAINT fk_lotes_afetados_ocorrencia REFERENCES ocorrencias (id) ON DELETE CASCADE,
    lote_id BIGINT NOT NULL CONSTRAINT fk_lotes_afetados_lote REFERENCES lotes (id),
    codigo_lote VARCHAR(40) NOT NULL,
    imunobiologico VARCHAR(100) NOT NULL,
    quantidade INT NOT NULL CONSTRAINT chk_lotes_afetados_quantidade CHECK (quantidade >= 0),
    -- Nenhum lote aparece duas vezes na mesma ocorrência.
    CONSTRAINT pk_ocorrencia_lotes PRIMARY KEY (ocorrencia_id, lote_id)
);

CREATE INDEX idx_lotes_afetados_lote ON ocorrencia_lotes (lote_id);
